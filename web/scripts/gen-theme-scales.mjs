// Generates src/theme-scales.css: theme-aware "r g b" variables for the
// Tailwind meaning colours used in badges, chips and toasts. Dark keeps
// each shade; light flips it so tinted badges written dark-first
// (bg-X-900/50 text-X-300 border-X-700) stay readable on white:
//   text  200 -> 800, 300 -> 700, 400 -> 700
//   fills 900 -> 100, 800 -> 200 ; 600/700 unchanged (solid buttons, borders)
// Run: node scripts/gen-theme-scales.mjs   (committed output, deterministic)
import colors from 'tailwindcss/colors.js'
import { writeFileSync } from 'node:fs'

const NAMES = ['green', 'emerald', 'yellow', 'amber', 'red', 'sky', 'blue', 'purple', 'cyan', 'orange', 'pink', 'indigo', 'violet', 'rose', 'lime']
const SHADES = [200, 300, 400, 600, 700, 800, 900]
const LIGHT = { 200: 800, 300: 700, 400: 700, 600: 600, 700: 700, 800: 200, 900: 100 }

const rgb = (hex) => hex.slice(1).match(/../g).map((h) => parseInt(h, 16)).join(' ')
let dark = ':root {\n'
let light = 'html:not(.dark) {\n'
for (const n of NAMES) {
  for (const s of SHADES) {
    dark += `  --tw-${n}-${s}: ${rgb(colors[n][s])};\n`
    light += `  --tw-${n}-${s}: ${rgb(colors[n][LIGHT[s]])};\n`
  }
}
const css = `/* Generated by scripts/gen-theme-scales.mjs. Do not edit. */\n${dark}}\n\n${light}}\n`
writeFileSync(new URL('../src/theme-scales.css', import.meta.url), css)
console.log('wrote src/theme-scales.css')
